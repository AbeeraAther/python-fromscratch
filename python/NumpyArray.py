
#numerical python
import numpy as np

arr = np.array([10, 20, 30, 40, 50])
print("array in numpy:")
print(arr*2)
print(type(arr))
print(arr.shape)  
print(arr.ndim)    
print(arr.size)    
print(arr.dtype)  
print(np.sqrt(arr))     
print(np.sum(arr))      
print(np.mean(arr))    
print(np.max(arr))     
print(np.min(arr)) 

